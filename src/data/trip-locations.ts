export function localizeTripLocations(locations: TripLocation[], locale: Locale): TripLocation[] {
  if (locale !== "en-US") {
    return locations;
  }

  return locations.map((location) => ({
    ...location,
    note: location.note ? (englishNoteByChineseNote[location.note] ?? location.note) : undefined,
  }));
}
